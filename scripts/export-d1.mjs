import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { DERIVED_TABLES_SQL, EDGES_DDL, SOURCES_DDL, STATS_DDL } from '../src/store/queries.ts';

const { DatabaseSync } = createRequire(import.meta.url)('node:sqlite');
const dbPath = process.env.KB_DB_PATH ?? 'C:\\Project\\kb\\data\\kb.db';
const outFile = process.argv[2] ?? 'dist/d1-import.sql';

const db = new DatabaseSync(dbPath, { readOnly: true });
db.exec(DERIVED_TABLES_SQL);

const SERVED = "'leetcode','hld','system-design','ai'";
const OK_SOURCE = "s.display_mode IN ('full','link')";
const RESOURCE_OK = `r.category IN (${SERVED}) AND ${OK_SOURCE}`;

// Parents before children; each entry is the table and the query that selects the rows to export.
const tables = [
  ['sources', `SELECT s.id, s.name, CASE WHEN s.repo_url LIKE 'local:%' THEN 'unknown' ELSE s.repo_url END AS repo_url, s.commit_sha, s.license, s.author, s.display_mode, s.license_text, s.notice_text, s.copyright_notice, s.adapted, s.adaptation_note FROM sources s WHERE ${OK_SOURCE} ORDER BY s.id`],
  ['companies', 'SELECT * FROM companies ORDER BY id'],
  ['resources', `SELECT r.id, r.source_id, r.slug, r.title, r.category, r.topics, r.level, CASE WHEN r.url LIKE 'local:%' THEN '' ELSE r.url END AS url,
      CASE WHEN s.display_mode = 'full' THEN r.content_md END AS content_md, r.file_path
    FROM resources r JOIN sources s ON s.id = r.source_id WHERE ${RESOURCE_OK} ORDER BY r.id`],
  ['company_resources', `SELECT cr.* FROM company_resources cr JOIN resources r ON r.id = cr.resource_id JOIN sources s ON s.id = r.source_id
    WHERE ${RESOURCE_OK} ORDER BY cr.company_id, cr.resource_id, cr."window"`],
  ['question_solutions', `SELECT qs.* FROM question_solutions qs JOIN sources s ON s.id = qs.source_id JOIN resources r ON r.id = qs.question_id
    JOIN sources rs ON rs.id = r.source_id WHERE qs.approved = 1 AND ${OK_SOURCE} AND r.category IN (${SERVED}) AND rs.display_mode IN ('full','link') ORDER BY qs.id`],
  ['company_profiles', `SELECT t.* FROM company_profiles t JOIN sources s ON s.id = t.source_id WHERE ${OK_SOURCE} ORDER BY t.company_id`],
  ['company_values', `SELECT t.* FROM company_values t JOIN sources s ON s.id = t.source_id WHERE ${OK_SOURCE} ORDER BY t.id`],
  ['behavioral_topics', `SELECT t.* FROM behavioral_topics t JOIN sources s ON s.id = t.source_id WHERE ${OK_SOURCE} ORDER BY t.rowid`],
  ['company_stats', 'SELECT * FROM temp.company_stats ORDER BY company_id'],
  ['company_edges', 'SELECT * FROM temp.company_edges ORDER BY company_a, company_b'],
  ['company_sources', 'SELECT * FROM temp.company_sources ORDER BY company_id, source_id'],
];

const literal = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' || typeof v === 'bigint' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const MAX_ROWS = 100;
const MAX_CHARS = 60_000;

const ddl = (table) =>
  table === 'company_stats'
    ? STATS_DDL
    : table === 'company_edges'
    ? EDGES_DDL
    : table === 'company_sources'
    ? SOURCES_DDL
    : db.prepare("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?").get(table).sql.replace('content_md TEXT NOT NULL', 'content_md TEXT').replace("CHECK (url <> '')", '');
const indexes = (table) => db.prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND tbl_name = ? AND sql IS NOT NULL").all(table).map((r) => r.sql);

const header = '-- generated by scripts/export-d1.mjs; hidden sources skipped, content_md kept only for display_mode = full';
const schema = [];
const out = [];
for (const [table] of [...tables].reverse()) schema.push(`DROP TABLE IF EXISTS ${table};`);
const summary = {};
for (const [table, query] of tables) {
  schema.push(`${ddl(table)};`);
  const rows = db.prepare(query).all();
  summary[table] = rows.length;
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  const head = `INSERT INTO ${table} (${cols.map((c) => `"${c}"`).join(', ')}) VALUES\n`;
  let chunk = [], size = 0;
  const flush = () => { if (chunk.length) out.push(`${head}${chunk.join(',\n')};`); chunk = []; size = 0; };
  for (const row of rows) {
    const tuple = `(${cols.map((c) => literal(row[c])).join(', ')})`;
    if (chunk.length >= MAX_ROWS || size + tuple.length > MAX_CHARS) flush();
    chunk.push(tuple);
    size += tuple.length;
  }
  flush();
}
const indexSql = tables.flatMap(([table]) => indexes(table).map((sql) => `${sql};`));

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, `${[header, ...schema, ...out, ...indexSql].join('\n')}\n`);

const chunkDir = process.argv[3];
if (chunkDir) {
  mkdirSync(chunkDir, { recursive: true });
  const MAX_FILE = 900_000;
  const files = [['000-schema', schema]];
  let cur = [], size = 0;
  for (const stmt of out) {
    if (cur.length && size + stmt.length > MAX_FILE) { files.push([`${String(files.length).padStart(3, '0')}-data`, cur]); cur = []; size = 0; }
    cur.push(stmt);
    size += stmt.length;
  }
  if (cur.length) files.push([`${String(files.length).padStart(3, '0')}-data`, cur]);
  files.push([`${String(files.length).padStart(3, '0')}-indexes`, indexSql]);
  for (const [name, stmts] of files) writeFileSync(path.join(chunkDir, `${name}.sql`), `${stmts.join('\n')}\n`);
  console.log(`wrote ${files.length} chunk files to ${chunkDir}`);
}

const hidden = db.prepare("SELECT COUNT(*) AS n FROM sources WHERE display_mode NOT IN ('full','link')").get().n;
console.log(`wrote ${outFile} from ${dbPath}`);
console.log(`skipped ${hidden} hidden source(s); rows exported:`, summary);
console.log('next: npx wrangler d1 execute roundwise --remote --file', outFile);
